/* the decoding tree: internal nodes hold child indices, leaves -(sym + 1) */
static int h2_huff_tree[600][2];
static int h2_huff_nodes = 0;

static void h2_huff_add(uint32_t code, int len, int sym) {
    int n = 0;
    for (int k = len - 1; k >= 0; k--) {
        int bit = (int)((code >> k) & 1);
        if (k == 0) {
            h2_huff_tree[n][bit] = -(sym + 1);
        } else {
            if (h2_huff_tree[n][bit] == 0) {
                h2_huff_tree[h2_huff_nodes][0] = h2_huff_tree[h2_huff_nodes][1] = 0;
                h2_huff_tree[n][bit] = h2_huff_nodes++;
            }
            n = h2_huff_tree[n][bit];
        }
    }
}

static int h2_huff_decode(const unsigned char *p, size_t n, h2_buf *out) {
    if (!h2_huff_nodes) {
        h2_huff_nodes = 1;
        h2_huff_tree[0][0] = h2_huff_tree[0][1] = 0;
        for (int s = 0; s < 256; s++) h2_huff_add(fwp_huff_codes[s], fwp_huff_lens[s], s);
        h2_huff_add(0x3fffffffu, 30, 256);
    }
    int node = 0, pending = 0, ones = 1;
    for (size_t i = 0; i < n; i++) {
        for (int k = 7; k >= 0; k--) {
            int bit = (p[i] >> k) & 1;
            pending++;
            ones &= bit;
            int next = h2_huff_tree[node][bit];
            if (next < 0) {
                int sym = -next - 1;
                if (sym == 256) return h2_fail("hpack: EOS in Huffman string");
                h2b_byte(out, (unsigned)sym);
                node = 0;
                pending = 0;
                ones = 1;
            } else if (next == 0) {
                return h2_fail("hpack: bad Huffman code");
            } else {
                node = next;
            }
        }
    }
    if (pending > 7 || !ones) return h2_fail("hpack: bad Huffman padding");
    return 1;
}

typedef struct { char *name, *value; } h2_hdr;
typedef struct { h2_hdr *v; size_t n, cap; } h2_hdrs;

static void h2_hdrs_add(h2_hdrs *h, const char *name, size_t nl, const char *value, size_t vl) {
    if (h->n == h->cap) {
        h->cap = h->cap ? h->cap * 2 : 8;
        h->v = (h2_hdr *)realloc(h->v, h->cap * sizeof(h2_hdr));
    }
    h2_hdr *e = &h->v[h->n++];
    e->name = (char *)malloc(nl + 1);
    memcpy(e->name, name, nl);
    e->name[nl] = 0;
    e->value = (char *)malloc(vl + 1);
    memcpy(e->value, value, vl);
    e->value[vl] = 0;
}

static void h2_hdrs_free(h2_hdrs *h) {
    for (size_t i = 0; i < h->n; i++) { free(h->v[i].name); free(h->v[i].value); }
    free(h->v);
    h->v = 0;
    h->n = h->cap = 0;
}

/* the value of the last header with this name, or 0 */
static const char *h2_get(const h2_hdrs *h, const char *name) {
    for (size_t i = h->n; i > 0; i--)
        if (strcmp(h->v[i - 1].name, name) == 0) return h->v[i - 1].value;
    return 0;
}

/* a decoder: the dynamic table (newest first) and its size */
typedef struct { h2_hdrs t; size_t size, max, limit; } h2_hpack;

static void h2_hpack_init(h2_hpack *d) { memset(d, 0, sizeof *d); d->max = d->limit = 4096; }
static void h2_hpack_free(h2_hpack *d) { h2_hdrs_free(&d->t); }

static void h2_hpack_evict(h2_hpack *d) {
    while (d->size > d->max && d->t.n > 0) {
        h2_hdr *e = &d->t.v[d->t.n - 1];
        d->size -= strlen(e->name) + strlen(e->value) + 32;
        free(e->name);
        free(e->value);
        d->t.n--;
    }
}

static void h2_hpack_insert(h2_hpack *d, const char *name, const char *value) {
    h2_hdrs_add(&d->t, name, strlen(name), value, strlen(value));
    h2_hdr e = d->t.v[d->t.n - 1];
    memmove(d->t.v + 1, d->t.v, (d->t.n - 1) * sizeof(h2_hdr));
    d->t.v[0] = e;
    d->size += strlen(name) + strlen(value) + 32;
    h2_hpack_evict(d);
}

static int h2_hpack_entry(h2_hpack *d, uint64_t i, const char **name, const char **value) {
    if (i == 0) return h2_fail("hpack: index 0");
    if (i <= 61) { *name = h2_static[i - 1][0]; *value = h2_static[i - 1][1]; return 1; }
    if (i - 62 >= d->t.n) return h2_fail("hpack: index %llu out of range", (unsigned long long)i);
    *name = d->t.v[i - 62].name;
    *value = d->t.v[i - 62].value;
    return 1;
}

static int h2_int(const unsigned char *b, size_t n, size_t *i, int prefix, uint64_t *x) {
    uint64_t mask = ((uint64_t)1 << prefix) - 1;
    if (*i >= n) return h2_fail("hpack: truncated");
    *x = b[(*i)++] & mask;
    if (*x < mask) return 1;
    for (int shift = 0;; shift += 7) {
        if (*i >= n) return h2_fail("hpack: truncated integer");
        if (shift > 56) return h2_fail("hpack: integer overflow");
        unsigned char c = b[(*i)++];
        *x += (uint64_t)(c & 0x7f) << shift;
        if (!(c & 0x80)) return 1;
    }
}

/* a string literal, NUL-terminated in `out` */
static int h2_str(const unsigned char *b, size_t n, size_t *i, h2_buf *out) {
    out->len = 0;
    if (*i >= n) return h2_fail("hpack: truncated");
    int huff = b[*i] & 0x80;
    uint64_t len;
    if (!h2_int(b, n, i, 7, &len)) return 0;
    if (len > n - *i) return h2_fail("hpack: truncated string");
    if (huff) { if (!h2_huff_decode(b + *i, (size_t)len, out)) return 0; }
    else h2b_put(out, b + *i, (size_t)len);
    *i += (size_t)len;
    h2b_byte(out, 0);
    out->len--;
    return 1;
}

static int h2_hpack_decode(h2_hpack *d, const unsigned char *b, size_t n, h2_hdrs *out) {
    size_t i = 0;
    h2_buf name = {0}, value = {0};
    int ok = 1;
    while (ok && i < n) {
        unsigned char c = b[i];
        uint64_t x;
        const char *nm, *vl;
        if (c & 0x80) {
            ok = h2_int(b, n, &i, 7, &x) && h2_hpack_entry(d, x, &nm, &vl);
            if (ok) h2_hdrs_add(out, nm, strlen(nm), vl, strlen(vl));
        } else if ((c & 0xe0) == 0x20) {
            ok = h2_int(b, n, &i, 5, &x);
            if (ok && x > d->limit) ok = h2_fail("hpack: table size update above the limit");
            if (ok) { d->max = (size_t)x; h2_hpack_evict(d); }
        } else {
            int indexing = (c & 0x40) != 0;
            ok = h2_int(b, n, &i, indexing ? 6 : 4, &x);
            if (!ok) break;
            if (x == 0) {
                ok = h2_str(b, n, &i, &name);
            } else {
                ok = h2_hpack_entry(d, x, &nm, &vl);
                name.len = 0;
                if (ok) { h2b_put(&name, nm, strlen(nm) + 1); name.len--; }
            }
            ok = ok && h2_str(b, n, &i, &value);
            if (!ok) break;
            h2_hdrs_add(out, (char *)name.d, name.len, (char *)value.d, value.len);
            if (indexing) h2_hpack_insert(d, (char *)name.d, (char *)value.d);
        }
    }
    h2b_free(&name);
    h2b_free(&value);
    return ok;
}

static void h2_put_int(h2_buf *b, unsigned flags, int prefix, uint64_t x) {
    uint64_t max = ((uint64_t)1 << prefix) - 1;
    if (x < max) { h2b_byte(b, flags | (unsigned)x); return; }
    h2b_byte(b, flags | (unsigned)max);
    x -= max;
    while (x >= 128) { h2b_byte(b, (unsigned)(x % 128) | 0x80); x /= 128; }
    h2b_byte(b, (unsigned)x);
}

/* a literal header field without indexing, with a new name */
static void h2_hpack_lit(h2_buf *b, const char *name, const char *value) {
    size_t nl = strlen(name), vl = strlen(value);
    h2b_byte(b, 0);
    h2_put_int(b, 0, 7, nl);
    h2b_put(b, name, nl);
    h2_put_int(b, 0, 7, vl);
    h2b_put(b, value, vl);
}

/* ------------------------------------------------------------------- frames */

enum { H2_DATA = 0, H2_HEADERS = 1, H2_RST_STREAM = 3, H2_SETTINGS = 4, H2_PING = 6, H2_GOAWAY = 7,
       H2_WINDOW_UPDATE = 8, H2_CONTINUATION = 9 };
enum { H2_END_STREAM = 1, H2_ACK = 1, H2_END_HEADERS = 4, H2_PADDED = 8, H2_PRIORITY = 0x20 };
#define H2_OUR_WINDOW (1u << 30)
#define H2_MAX_FRAME (1u << 24)
static const char h2_preface[] = "PRI * HTTP/2.0\r\n\r\nSM\r\n\r\n";

static void h2_frame(h2_buf *b, int type, int flags, uint32_t stream, const void *p, size_t n) {
    unsigned char h[9] = {(unsigned char)(n >> 16), (unsigned char)(n >> 8), (unsigned char)n, (unsigned char)type,
                          (unsigned char)flags, (unsigned char)((stream >> 24) & 0x7f), (unsigned char)(stream >> 16),
                          (unsigned char)(stream >> 8), (unsigned char)stream};
    h2b_put(b, h, 9);
    h2b_put(b, p, n);
}

typedef struct { int type, flags; uint32_t stream; const unsigned char *p; size_t n; } h2_fr;

/* 1: a frame of `size` bytes is at the start of the buffer; 0: need more;
 * -1: malformed */
static int h2_parse(const h2_buf *b, h2_fr *f, size_t *size) {
    if (b->len < 9) return 0;
    size_t n = (size_t)b->d[0] << 16 | (size_t)b->d[1] << 8 | b->d[2];
    if (n > H2_MAX_FRAME) return -1;
    if (b->len < 9 + n) return 0;
    f->type = b->d[3];
    f->flags = b->d[4];
    f->stream = h2_rd32(b->d + 5) & 0x7fffffffu;
    f->p = b->d + 9;
    f->n = n;
    *size = 9 + n;
    return 1;
}

/* the payload of DATA or HEADERS without padding and priority */
static int h2_unpad(const h2_fr *f, const unsigned char **p, size_t *n) {
    *p = f->p;
    *n = f->n;
    size_t pad = 0;
    if (f->flags & H2_PADDED) {
        if (*n < 1) return 0;
        pad = (*p)[0];
        (*p)++;
        (*n)--;
    }
    if (f->type == H2_HEADERS && (f->flags & H2_PRIORITY)) {
        if (*n < 5) return 0;
        *p += 5;
        *n -= 5;
    }
    if (pad > *n) return 0;
    *n -= pad;
    return 1;
}

static void h2_header_frames(h2_buf *b, uint32_t stream, const h2_buf *block, int end_stream, size_t max) {
    size_t off = 0;
    int first = 1;
    do {
        size_t k = block->len - off > max ? max : block->len - off;
        int last = off + k == block->len;
        int flags = last ? H2_END_HEADERS : 0;
        if (first && end_stream) flags |= H2_END_STREAM;
        h2_frame(b, first ? H2_HEADERS : H2_CONTINUATION, flags, stream, block->d ? block->d + off : 0, k);
        off += k;
        first = 0;
    } while (off < block->len);
}

static void h2_our_settings(h2_buf *b) {
    unsigned char s[12] = {0, 2, 0, 0, 0, 0, 0, 4, 0, 0, 0, 0};
    s[8] = (unsigned char)(H2_OUR_WINDOW >> 24);
    s[9] = (unsigned char)(H2_OUR_WINDOW >> 16);
    s[10] = (unsigned char)(H2_OUR_WINDOW >> 8);
    s[11] = (unsigned char)H2_OUR_WINDOW;
    h2_frame(b, H2_SETTINGS, 0, 0, s, 12);
    h2_buf w = {0};
    h2b_be32(&w, H2_OUR_WINDOW - 65535);
    h2_frame(b, H2_WINDOW_UPDATE, 0, 0, w.d, 4);
    h2b_free(&w);
}

typedef struct { size_t max_frame; int64_t init_window; } h2_peer;

/* apply a SETTINGS payload; *delta is the change of the initial window */
static int h2_settings(h2_peer *pe, const unsigned char *p, size_t n, int64_t *delta) {
    *delta = 0;
    if (n % 6) return h2_fail("bad SETTINGS frame");
    for (size_t i = 0; i < n; i += 6) {
        unsigned id = (unsigned)p[i] << 8 | p[i + 1];
        uint32_t v = h2_rd32(p + i + 2);
        if (id == 4) {
            if (v > 0x7fffffffu) return h2_fail("bad initial window size");
            *delta += (int64_t)v - pe->init_window;
            pe->init_window = v;
        } else if (id == 5) {
            if (v < 16384 || v > 16777215) return h2_fail("bad max frame size");
            pe->max_frame = v;
        }
    }
    return 1;
}

/* --------------------------------------------------------------------- gRPC */

enum { GRPC_OK = 0, GRPC_CANCELLED = 1, GRPC_UNKNOWN = 2, GRPC_INVALID_ARGUMENT = 3, GRPC_DEADLINE_EXCEEDED = 4,
       GRPC_NOT_FOUND = 5, GRPC_FAILED_PRECONDITION = 9, GRPC_UNIMPLEMENTED = 12, GRPC_INTERNAL = 13,
       GRPC_UNAVAILABLE = 14 };

static void h2_grpc_frame(h2_buf *b, const unsigned char *msg, size_t n) {
    h2b_byte(b, 0);
    h2b_be32(b, (uint32_t)n);
    h2b_put(b, msg, n);
}

static int h2_grpc_unframe(const h2_buf *body, const unsigned char **msg, size_t *n) {
    if (body->len < 5) return h2_fail("missing gRPC message");
    if (body->d[0] != 0) return h2_fail("compressed gRPC messages are not supported");
    *n = h2_rd32(body->d + 1);
    if (body->len != 5 + *n) return h2_fail("expected exactly one gRPC message");
    *msg = body->d + 5;
    return 1;
}

static void h2_pct_encode(h2_buf *b, const char *s) {
    static const char hex[] = "0123456789ABCDEF";
    for (; *s; s++) {
        unsigned char c = (unsigned char)*s;
        if (c >= 0x20 && c < 0x7f && c != '%') h2b_byte(b, c);
        else { h2b_byte(b, '%'); h2b_byte(b, (unsigned)hex[c >> 4]); h2b_byte(b, (unsigned)hex[c & 15]); }
    }
    h2b_byte(b, 0);
    b->len--;
}

static int h2_hexval(char c) {
    if (c >= '0' && c <= '9') return c - '0';
    if (c >= 'a' && c <= 'f') return c - 'a' + 10;
    if (c >= 'A' && c <= 'F') return c - 'A' + 10;
    return -1;
}

static void h2_pct_decode(char *s) {
    char *w = s;
    for (const char *r = s; *r;) {
        if (r[0] == '%' && r[1] && r[2] && h2_hexval(r[1]) >= 0 && h2_hexval(r[2]) >= 0) {
            *w++ = (char)(h2_hexval(r[1]) * 16 + h2_hexval(r[2]));
            r += 3;
        } else {
            *w++ = *r++;
        }
    }
    *w = 0;
}

/* -------------------------------------------------------------- listening */

/* bind "host:port"; the bound address is written to `bound` */
static int h2_listen(const char *addr, char *bound, size_t bn) {
    char host[256];
    const char *colon = strrchr(addr, ':');
    if (!colon || (size_t)(colon - addr) >= sizeof host) { h2_fail("bad address `%s`", addr); return -1; }
    memcpy(host, addr, (size_t)(colon - addr));
    host[colon - addr] = 0;
    char *h = host;
    if (h[0] == '[' && h[strlen(h) - 1] == ']') { h[strlen(h) - 1] = 0; h++; }
    struct addrinfo hints, *res = 0;
    memset(&hints, 0, sizeof hints);
    hints.ai_family = AF_UNSPEC;
    hints.ai_socktype = SOCK_STREAM;
    hints.ai_flags = AI_PASSIVE;
    int rc = getaddrinfo(*h ? h : 0, colon + 1, &hints, &res);
    if (rc != 0) { h2_fail("cannot resolve %s: %s", addr, gai_strerror(rc)); return -1; }
    int fd = -1, err = 0;
    for (struct addrinfo *a = res; a; a = a->ai_next) {
        fd = socket(a->ai_family, a->ai_socktype | SOCK_CLOEXEC, a->ai_protocol);
        if (fd < 0) { err = errno; continue; }
        int one = 1;
        setsockopt(fd, SOL_SOCKET, SO_REUSEADDR, &one, sizeof one);
        if (bind(fd, a->ai_addr, a->ai_addrlen) == 0 && listen(fd, 128) == 0) break;
        err = errno;
        close(fd);
        fd = -1;
    }
    freeaddrinfo(res);
    if (fd < 0) { h2_fail("cannot listen on %s: %s", addr, strerror(err)); return -1; }
    struct sockaddr_storage ss;
    socklen_t sl = sizeof ss;
    char hb[128], pb[16];
    if (getsockname(fd, (struct sockaddr *)&ss, &sl) == 0 &&
        getnameinfo((struct sockaddr *)&ss, sl, hb, sizeof hb, pb, sizeof pb, NI_NUMERICHOST | NI_NUMERICSERV) == 0)
        snprintf(bound, bn, ss.ss_family == AF_INET6 ? "[%s]:%s" : "%s:%s", hb, pb);
    else
        snprintf(bound, bn, "%s", addr);
    return fd;
}

/* ----------------------------------------------------------------- protobuf */

/* Schema kinds (src/protobuf.rs, Schema::flatten). */
enum { PB_BOOL, PB_SINT, PB_UINT, PB_F32, PB_F64, PB_STR, PB_BYTES, PB_INT128, PB_MSG, PB_ONEOF, PB_LIST, PB_OPT };

typedef struct { const unsigned char *d; size_t n, i; } pb_rd;

static int pb_take(pb_rd *r, size_t k, const unsigned char **p) {
    if (k > r->n - r->i) return h2_fail("truncated value");
    *p = r->d + r->i;
    r->i += k;
    return 1;
}

static int pb_leb(pb_rd *r, uint64_t *x) {
    *x = 0;
    for (int shift = 0; shift < 64; shift += 7) {
        const unsigned char *b;
        if (!pb_take(r, 1, &b)) return 0;
        *x |= (uint64_t)(b[0] & 0x7f) << shift;
        if (!(b[0] & 0x80)) return 1;
    }
    return h2_fail("bad varint");
}

static void pb_varint(h2_buf *b, uint64_t x) {
    while (x >= 0x80) { h2b_byte(b, (unsigned)(x & 0x7f) | 0x80); x >>= 7; }
    h2b_byte(b, (unsigned)x);
}

static void pb_key(h2_buf *b, uint32_t num, int wire) { pb_varint(b, (uint64_t)num << 3 | (unsigned)wire); }

static int pb_le(pb_rd *r, int w, uint64_t *x) {
    const unsigned char *p;
    if (!pb_take(r, (size_t)w, &p)) return 0;
    *x = 0;
    for (int i = 0; i < w; i++) *x |= (uint64_t)p[i] << (8 * i);
    return 1;
}

static int pb_packable(const int *S, int node) { int k = S[node]; return k <= PB_F64; }

/* a scalar: wire type, bytes in *b, and whether it is the default */
static int pb_enc_scalar(const int *S, int node, pb_rd *r, h2_buf *b, int *wire, int *dflt) {
    uint64_t x;
    const unsigned char *p;
    switch (S[node]) {
    case PB_BOOL:
        if (!pb_leb(r, &x)) return 0;
        pb_varint(b, x); *wire = 0; *dflt = x == 0; return 1;
    case PB_SINT: {
        int w = S[node + 1];
        if (!pb_le(r, w, &x)) return 0;
        int shift = 64 - 8 * w;
        int64_t v = (int64_t)(x << shift) >> shift;
        pb_varint(b, ((uint64_t)v << 1) ^ (uint64_t)(v >> 63)); *wire = 0; *dflt = v == 0; return 1;
    }
    case PB_UINT:
        if (!pb_le(r, S[node + 1], &x)) return 0;
        pb_varint(b, x); *wire = 0; *dflt = x == 0; return 1;
    case PB_F32: case PB_F64: {
        int w = S[node] == PB_F32 ? 4 : 8;
        if (!pb_take(r, (size_t)w, &p)) return 0;
        h2b_put(b, p, (size_t)w);
        *wire = w == 4 ? 5 : 1;
        *dflt = 1;
        for (int i = 0; i < w; i++) if (p[i]) *dflt = 0;
        return 1;
    }
    case PB_STR: case PB_BYTES:
        if (!pb_leb(r, &x) || !pb_take(r, (size_t)x, &p)) return 0;
        pb_varint(b, x); h2b_put(b, p, (size_t)x); *wire = 2; *dflt = x == 0; return 1;
    case PB_INT128:
        if (!pb_take(r, 16, &p)) return 0;
        pb_varint(b, 16); h2b_put(b, p, 16); *wire = 2;
        *dflt = 1;
        for (int i = 0; i < 16; i++) if (p[i]) *dflt = 0;
        return 1;
    }
    return h2_fail("internal: not a scalar");
}

static int pb_enc_body(const int *S, int node, pb_rd *r, h2_buf *out);

static int pb_enc_field(const int *S, uint32_t num, int node, pb_rd *r, h2_buf *out, int presence) {
    uint64_t x;
    switch (S[node]) {
    case PB_MSG: case PB_ONEOF: {
        h2_buf sub = {0};
        int ok = pb_enc_body(S, node, r, &sub);
        if (ok) { pb_key(out, num, 2); pb_varint(out, sub.len); h2b_put(out, sub.d, sub.len); }
        h2b_free(&sub);
        return ok;
    }
    case PB_LIST: {
        int c = S[node + 1];
        if (!pb_leb(r, &x)) return 0;
        if (pb_packable(S, c)) {
            h2_buf buf = {0};
            int wire, dflt, ok = 1;
            for (uint64_t i = 0; ok && i < x; i++) ok = pb_enc_scalar(S, c, r, &buf, &wire, &dflt);
            if (ok && x > 0) { pb_key(out, num, 2); pb_varint(out, buf.len); h2b_put(out, buf.d, buf.len); }
            h2b_free(&buf);
            return ok;
        }
        for (uint64_t i = 0; i < x; i++) if (!pb_enc_field(S, num, c, r, out, 1)) return 0;
        return 1;
    }
    case PB_OPT:
        if (!pb_leb(r, &x)) return 0;
        return x == 1 ? pb_enc_field(S, num, S[node + 1], r, out, 1) : 1;
    default: {
        h2_buf b = {0};
        int wire, dflt;
        int ok = pb_enc_scalar(S, node, r, &b, &wire, &dflt);
        if (ok && (presence || !dflt)) { pb_key(out, num, wire); h2b_put(out, b.d, b.len); }
        h2b_free(&b);
        return ok;
    }
    }
}

static int pb_enc_body(const int *S, int node, pb_rd *r, h2_buf *out) {
    int n = S[node + 1];
    if (S[node] == PB_MSG) {
        /* canonical order in, field number order out */
        h2_buf *parts = (h2_buf *)calloc((size_t)n + 1, sizeof(h2_buf));
        int ok = 1;
        for (int i = 0; ok && i < n; i++)
            ok = pb_enc_field(S, (uint32_t)S[node + 2 + 2 * i], S[node + 3 + 2 * i], r, &parts[i], 0);
        for (int done = 0; ok && done < n; done++) {
            int best = -1;
            for (int i = 0; i < n; i++)
                if (parts[i].cap != (size_t)-1 && (best < 0 || S[node + 2 + 2 * i] < S[node + 2 + 2 * best])) best = i;
            h2b_put(out, parts[best].d, parts[best].len);
            h2b_free(&parts[best]);
            parts[best].cap = (size_t)-1;
        }
        for (int i = 0; i < n; i++) if (parts[i].cap != (size_t)-1) h2b_free(&parts[i]);
        free(parts);
        return ok;
    }
    if (S[node] == PB_ONEOF) {
        uint64_t tag;
        if (!pb_leb(r, &tag)) return 0;
        if (tag >= (uint64_t)n) return h2_fail("bad constructor tag");
        return pb_enc_field(S, (uint32_t)tag + 1, S[node + 2 + (int)tag], r, out, 1);
    }
    return h2_fail("internal: not a message");
}

/* canonical bytes -> the body of message node `node` */
static int pb_encode(const int *S, int node, const unsigned char *canon, size_t n, h2_buf *out) {
    pb_rd r = {canon, n, 0};
    if (!pb_enc_body(S, node, &r, out)) return 0;
    if (r.i != n) return h2_fail("trailing bytes after value");
    return 1;
}

/* a field on the wire */
typedef struct { uint32_t num; int wire; uint64_t v; const unsigned char *p; size_t n; } pb_field;

/* the next field of a body: 1, 0 at the end, -1 malformed */
static int pb_next(const unsigned char *b, size_t n, size_t *i, pb_field *f) {
    if (*i >= n) return 0;
    pb_rd r = {b, n, *i};
    uint64_t k;
    if (!pb_leb(&r, &k)) return -1;
    if ((k >> 3) == 0 || (k >> 3) > 0xffffffffu) { h2_fail("bad field number"); return -1; }
    f->num = (uint32_t)(k >> 3);
    f->wire = (int)(k & 7);
    switch (f->wire) {
    case 0: if (!pb_leb(&r, &f->v)) return -1; break;
    case 1: if (!pb_le(&r, 8, &f->v)) return -1; break;
    case 5: if (!pb_le(&r, 4, &f->v)) return -1; break;
    case 2:
        if (!pb_leb(&r, &f->v) || !pb_take(&r, (size_t)f->v, &f->p)) return -1;
        f->n = (size_t)f->v;
        break;
    default: h2_fail("unsupported wire type"); return -1;
    }
    *i = r.i;
    return 1;
}

static void pb_le_put(h2_buf *b, uint64_t x, int w) {
    for (int i = 0; i < w; i++) h2b_byte(b, (unsigned)(x >> (8 * i)) & 0xff);
}

static int pb_valid_utf8(const unsigned char *s, size_t n) {
    size_t i = 0;
    while (i < n) {
        unsigned char c = s[i];
        int k;
        uint32_t cp;
        if (c < 0x80) { i++; continue; }
        else if ((c & 0xe0) == 0xc0) { k = 1; cp = c & 0x1f; }
        else if ((c & 0xf0) == 0xe0) { k = 2; cp = c & 0x0f; }
        else if ((c & 0xf8) == 0xf0) { k = 3; cp = c & 0x07; }
        else return 0;
        if (i + (size_t)k >= n) return 0;
        for (int j = 1; j <= k; j++) {
            if ((s[i + (size_t)j] & 0xc0) != 0x80) return 0;
            cp = cp << 6 | (s[i + (size_t)j] & 0x3f);
        }
        if ((k == 1 && cp < 0x80) || (k == 2 && cp < 0x800) || (k == 3 && cp < 0x10000) || cp > 0x10ffff ||
            (cp >= 0xd800 && cp <= 0xdfff))
            return 0;
        i += (size_t)k + 1;
    }
    return 1;
}

static int pb_dec_scalar(const int *S, int node, uint32_t num, const pb_field *f, h2_buf *out) {
    int k = S[node];
    int want = (k == PB_F32) ? 5 : (k == PB_F64) ? 1 : (k >= PB_STR) ? 2 : 0;
    if (f->wire != want) return h2_fail("field %u: wrong wire type", num);
    switch (k) {
    case PB_BOOL: h2b_byte(out, f->v != 0); return 1;
    case PB_SINT: {
        int w = S[node + 1];
        int64_t v = (int64_t)(f->v >> 1) ^ -(int64_t)(f->v & 1);
        if (w < 8) {
            int64_t lim = (int64_t)1 << (8 * w - 1);
            if (v < -lim || v >= lim) return h2_fail("field %u: value out of range", num);
        }
        pb_le_put(out, (uint64_t)v, w);
        return 1;
    }
    case PB_UINT: {
        int w = S[node + 1];
        if (w < 8 && f->v >= ((uint64_t)1 << (8 * w))) return h2_fail("field %u: value out of range", num);
        pb_le_put(out, f->v, w);
        return 1;
    }
    case PB_F32: pb_le_put(out, f->v, 4); return 1;
    case PB_F64: pb_le_put(out, f->v, 8); return 1;
    case PB_STR:
        if (!pb_valid_utf8(f->p, f->n)) return h2_fail("field %u: invalid UTF-8", num);
        /* fall through */
    case PB_BYTES:
        pb_varint(out, f->n);
        h2b_put(out, f->p, f->n);
        return 1;
    case PB_INT128:
        if (f->n == 0) { for (int i = 0; i < 16; i++) h2b_byte(out, 0); return 1; }
        if (f->n != 16) return h2_fail("field %u: value out of range", num);
        h2b_put(out, f->p, 16);
        return 1;
    }
    return h2_fail("internal: not a scalar");
}

static int pb_dec_body(const int *S, int node, const unsigned char *b, size_t n, h2_buf *out);

static int pb_dec_value(const int *S, int node, uint32_t num, const pb_field *f, h2_buf *out) {
    if (S[node] == PB_MSG || S[node] == PB_ONEOF) {
        if (f->wire != 2) return h2_fail("field %u: wrong wire type", num);
        return pb_dec_body(S, node, f->p, f->n, out);
    }
    return pb_dec_scalar(S, node, num, f, out);
}

static int pb_default(const int *S, int node, uint32_t num, h2_buf *out) {
    switch (S[node]) {
    case PB_BOOL: case PB_STR: case PB_BYTES: case PB_LIST: case PB_OPT: h2b_byte(out, 0); return 1;
    case PB_SINT: case PB_UINT: for (int i = 0; i < S[node + 1]; i++) h2b_byte(out, 0); return 1;
    case PB_F32: for (int i = 0; i < 4; i++) h2b_byte(out, 0); return 1;
    case PB_F64: for (int i = 0; i < 8; i++) h2b_byte(out, 0); return 1;
    case PB_INT128: for (int i = 0; i < 16; i++) h2b_byte(out, 0); return 1;
    case PB_MSG:
        for (int i = 0; i < S[node + 1]; i++)
            if (!pb_default(S, S[node + 3 + 2 * i], (uint32_t)S[node + 2 + 2 * i], out)) return 0;
        return 1;
    }
    return h2_fail("field %u: missing value", num);
}

static int pb_dec_field(const int *S, uint32_t num, int node, const unsigned char *b, size_t n, h2_buf *out) {
    size_t i = 0;
    pb_field f, last;
    int have = 0, r;
    if (S[node] == PB_LIST) {
        int c = S[node + 1];
        h2_buf buf = {0};
        uint64_t count = 0;
        int ok = 1;
        while (ok && (r = pb_next(b, n, &i, &f)) > 0) {
            if (f.num != num) continue;
            if (f.wire == 2 && pb_packable(S, c)) {
                pb_rd pr = {f.p, f.n, 0};
                while (ok && pr.i < pr.n) {
                    pb_field e;
                    e.num = num;
                    if (S[c] == PB_F32) { e.wire = 5; ok = pb_le(&pr, 4, &e.v); }
                    else if (S[c] == PB_F64) { e.wire = 1; ok = pb_le(&pr, 8, &e.v); }
                    else { e.wire = 0; ok = pb_leb(&pr, &e.v); }
                    ok = ok && pb_dec_scalar(S, c, num, &e, &buf);
                    count++;
                }
            } else {
                ok = pb_dec_value(S, c, num, &f, &buf);
                count++;
            }
        }
        if (ok && r < 0) ok = 0;
        if (ok) { pb_varint(out, count); h2b_put(out, buf.d, buf.len); }
        h2b_free(&buf);
        return ok;
    }
    while ((r = pb_next(b, n, &i, &f)) > 0)
        if (f.num == num) { last = f; have = 1; }
    if (r < 0) return 0;
    if (S[node] == PB_OPT) {
        if (!have) { h2b_byte(out, 0); return 1; }
        h2b_byte(out, 1);
        return pb_dec_value(S, S[node + 1], num, &last, out);
    }
    if (!have) return pb_default(S, node, num, out);
    return pb_dec_value(S, node, num, &last, out);
}

static int pb_dec_body(const int *S, int node, const unsigned char *b, size_t n, h2_buf *out) {
    int k = S[node + 1];
    if (S[node] == PB_MSG) {
        for (int i = 0; i < k; i++)
            if (!pb_dec_field(S, (uint32_t)S[node + 2 + 2 * i], S[node + 3 + 2 * i], b, n, out)) return 0;
        return 1;
    }
    if (S[node] == PB_ONEOF) {
        size_t i = 0;
        pb_field f, last;
        int have = 0, r;
        while ((r = pb_next(b, n, &i, &f)) > 0)
            if (f.num >= 1 && f.num <= (uint32_t)k) { last = f; have = 1; }
        if (r < 0) return 0;
        if (!have) return h2_fail("no alternative of a oneof is set");
        pb_varint(out, last.num - 1);
        return pb_dec_value(S, S[node + 2 + (int)last.num - 1], last.num, &last, out);
    }
    return h2_fail("internal: not a message");
}

/* the body of message node `node` -> canonical bytes */
static int pb_decode(const int *S, int node, const unsigned char *pb, size_t n, h2_buf *out) {
    return pb_dec_body(S, node, pb, n, out);
}

