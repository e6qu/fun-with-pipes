/* fwp runtime: gRPC over HTTP/2 cleartext (h2c, prior knowledge) and the
 * protobuf transcoder used by services (see docs/services.md).
 *
 *   - HPACK (RFC 7541): static and dynamic tables, Huffman decoding; the
 *     encoder writes literals without indexing.
 *   - HTTP/2 (RFC 9113): framing, SETTINGS, PING, WINDOW_UPDATE, GOAWAY,
 *     RST_STREAM, CONTINUATION and flow control.
 *   - gRPC: length-prefixed messages, grpc-status and grpc-message.
 *   - Protobuf: transcoding between the canonical binary encoding of fwp
 *     values and the protobuf wire format, driven by a schema of integers
 *     generated by the compiler (src/protobuf.rs, which implements the same
 *     algorithm for the interpreter).
 *
 * This file depends only on the C library, so the test suite can compile
 * it on its own (tests/services/h2_test.c). It is embedded only in
 * programs that call or serve services; connections, streams and calls,
 * on the task scheduler, are in fwp_rt_grpc.c. */

