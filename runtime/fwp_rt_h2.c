/* ------------------------------------------------------------------ buffers */

typedef struct { unsigned char *d; size_t len, cap; } h2_buf;

static void h2b_reserve(h2_buf *b, size_t n) {
    if (b->len + n <= b->cap) return;
    size_t c = b->cap ? b->cap : 256;
    while (c < b->len + n) c *= 2;
    b->d = (unsigned char *)realloc(b->d, c);
    if (!b->d) { fprintf(stderr, "fwp: out of memory\n"); exit(102); }
    b->cap = c;
}
static void h2b_put(h2_buf *b, const void *p, size_t n) {
    if (!n) return;
    h2b_reserve(b, n);
    memcpy(b->d + b->len, p, n);
    b->len += n;
}
static void h2b_byte(h2_buf *b, unsigned c) { unsigned char x = (unsigned char)c; h2b_put(b, &x, 1); }
static void h2b_drop(h2_buf *b, size_t n) {
    if (n >= b->len) { b->len = 0; return; }
    memmove(b->d, b->d + n, b->len - n);
    b->len -= n;
}
static void h2b_free(h2_buf *b) { free(b->d); b->d = 0; b->len = b->cap = 0; }
static void h2b_be32(h2_buf *b, uint32_t x) {
    unsigned char t[4] = {(unsigned char)(x >> 24), (unsigned char)(x >> 16), (unsigned char)(x >> 8), (unsigned char)x};
    h2b_put(b, t, 4);
}
static uint32_t h2_rd32(const unsigned char *p) {
    return (uint32_t)p[0] << 24 | (uint32_t)p[1] << 16 | (uint32_t)p[2] << 8 | p[3];
}

static char h2_err[512];
static int h2_fail(const char *fmt, ...) {
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(h2_err, sizeof h2_err, fmt, ap);
    va_end(ap);
    return 0;
}

