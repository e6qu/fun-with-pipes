"""Export a verified linear Git history for publication without runner secrets."""
from pathlib import Path
import base64,gzip,json,subprocess

def export_history(repository, base, head, destination):
    repository=Path(repository)
    def git(*args):return subprocess.check_output(['git',*args],cwd=repository)
    revisions=git('rev-list','--reverse',base+'..'+head).decode().splitlines()
    blobs={};commits=[];previous=base
    for revision in revisions:
        metadata=git('show','-s','--format=%H%n%P%n%T%n%an%n%ae%n%aI%n%cn%n%ce%n%cI%n%B',revision).decode().splitlines()
        assert metadata[0]==revision and metadata[1].split()==[previous]
        subject=metadata[9:]
        while subject and not subject[-1]:subject.pop()
        assert len(subject)==1 and len(subject[0])<=80
        assert not any(term in subject[0].lower() for term in
            ['co-authored','co authored','authored-by','authored by','ai attribution','generated by ai','generated by codex'])
        raw=git('diff-tree','--no-commit-id','--raw','-r','-z','--no-renames',previous,revision).split(b'\0')
        assert raw[-1]==b''
        delta=[]
        for index in range(0,len(raw)-1,2):
            old_mode,new_mode,old_sha,new_sha,status=raw[index].decode().split()
            old_mode=old_mode.removeprefix(':');path=raw[index+1].decode()
            assert old_mode in {'000000','100644','100755','120000'}
            assert new_mode in {'000000','100644','100755','120000'}
            if new_sha=='0'*40:
                delta.append(dict(path=path,mode=old_mode,type='blob',sha=None))
            else:
                delta.append(dict(path=path,mode=new_mode,type='blob',sha=new_sha))
                if new_sha not in blobs:
                    data=git('cat-file','blob',new_sha)
                    assert len(data)<2*1024*1024,(path,len(data))
                    blobs[new_sha]=base64.b64encode(data).decode()
        commits.append(dict(sha=revision,parent=previous,tree=metadata[2],
            author=dict(name=metadata[3],email=metadata[4],date=metadata[5]),
            committer=dict(name=metadata[6],email=metadata[7],date=metadata[8]),
            message=subject[0],delta=delta))
        previous=revision
    package=dict(base=base,head=head,tree=git('rev-parse',head+'^{tree}').decode().strip(),
                 commits=commits,blobs=blobs)
    encoded=json.dumps(package,separators=(',',':')).encode()
    assert len(encoded)<32*1024*1024,len(encoded)
    destination=Path(destination);destination.parent.mkdir(parents=True,exist_ok=True)
    with gzip.open(destination,'wb') as stream:stream.write(encoded)
    assert destination.stat().st_size<5*1024*1024
    return dict(tree=package['tree'],commits=len(commits),blobs=len(blobs),
                bytes=destination.stat().st_size,uncompressedBytes=len(encoded))
