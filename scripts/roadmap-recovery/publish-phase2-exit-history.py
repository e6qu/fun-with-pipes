"""Publish runner-verified Git objects with ordinary metadata and an exact lease."""
from pathlib import Path
import argparse,base64,gzip,hashlib,json,subprocess
from datetime import datetime
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--artifact',type=Path,required=True)
parser.add_argument('--run',type=int,required=True)
parser.add_argument('--driver',required=True)
parser.add_argument('--expected-old')
args=parser.parse_args()
REPO='repos/e6qu/fun-with-pipes'
def api(endpoint,payload=None,method='POST',graphql=False):
 argv=['gh','api', 'graphql' if graphql else REPO+endpoint]
 if payload is not None:
  path=Path('/private/tmp/fwp-repair-publication-api-input.json');path.write_text(json.dumps(payload));argv+=['--method',method,'--input',str(path)]
 return json.loads(subprocess.check_output(argv,text=True))
run=api('/actions/runs/'+str(args.run));assert run['head_sha']==args.driver
assert run['status']=='completed' and run['conclusion']=='success'
jobs=api('/actions/runs/'+str(args.run)+'/jobs')['jobs']
assert len(jobs)==1 and jobs[0]['status']=='completed' and jobs[0]['conclusion']=='success'
assert jobs[0]['name']=='repair'
manifest_path=args.artifact/'phase2-exit.json'
manifest=json.loads(manifest_path.read_text())
branch=manifest['branch'];assert branch=='ownership-exit-and-buffer-bundle'
archive=args.artifact/'prepared-commits.json.gz'
assert archive.stat().st_size<5*1024*1024
with gzip.open(archive,'rb') as stream:raw=stream.read(32*1024*1024+1)
assert len(raw)<32*1024*1024
package=json.loads(raw)
assert package['head']==manifest['head'] and package['tree']==manifest['tree']
assert package['base']==manifest['base']
proof=json.loads(Path('/private/tmp/fwp-pr124-merge-proof.json').read_text())
assert proof['acceptedHead']=='3aae99bfa705e26babc2cf251b0e583dfd95cf38' and proof['verification']=='GitHub verified signed commit payload'
assert manifest['base']==manifest['previous']==proof['sha']
assert api('/git/ref/heads/main')['object']['sha']==proof['sha']
assert len(package['commits'])==2
for key,head,names in [
 ('reviewEvidence','167d769deaa28fae9b361ba4e9fa33b443d1a79c',{'review ('+p+')' for p in ['ubuntu-latest','macos-15','macos-15-intel']}),
 ('arrayEvidence','296ea83b45bb153c2b86d1df68e05c799013b2eb',{'arrays ('+p+')' for p in ['ubuntu-latest','macos-15','macos-15-intel']}),
 ('kernelEvidence','28db5471d503763aa27e7da4f60c5ad880ad4183',{'kernels ('+p+')' for p in ['ubuntu-latest','macos-15','macos-15-intel']})]:
 r=manifest[key];assert r['headSha']==head and r['status']=='completed' and r['conclusion']=='success'
 assert len(r['jobs'])==3 and {j['name'] for j in r['jobs']}==names
 assert all(j['status']=='completed' and j['conclusion']=='success' for j in r['jobs'])
assert manifest['fallbackReport']['head']==package['head']
assert manifest['fallbackReport']['declarations']==177 and manifest['fallbackReport']['symbols']==167
assert manifest['inventoryReport']['head']==package['head']
assert manifest['inventoryReport']['counts']['contract']==168
assert manifest['inventoryReport']['reviewSymbols']==167
journal=args.artifact/'publication.json'
identity=dict(run=args.run,driver=args.driver,branch=branch,base=package['base'],
              exportedHead=package['head'],tree=package['tree'],
              exportHash=hashlib.sha256(archive.read_bytes()).hexdigest(),expectedOld=args.expected_old)
if journal.exists():
 state=json.loads(journal.read_text())
 assert state['identity']==identity
else:state=dict(identity=identity,blobs=[],commits=[])
def save():journal.write_text(json.dumps(state,indent=2)+'\n')
save()
if state.get('head'):
 assert api('/git/ref/heads/'+branch)['object']['sha']==state['head']
 assert api('/git/commits/'+state['head'])['tree']['sha']==identity['tree']
 print('Already published: '+state['head'],flush=True)
 raise SystemExit(0)
assert args.expected_old is None
assert api('/pulls/124')['merged'] and api('/pulls/124')['merge_commit_sha']==proof['sha']
# Publication changes only Git object metadata; builds/rebases stay on runners.
for number,(sha,content) in enumerate(package['blobs'].items(),1):
 data=base64.b64decode(content,validate=True)
 assert hashlib.sha1(b'blob '+str(len(data)).encode()+b'\0'+data).hexdigest()==sha
 if sha in state['blobs']:continue
 response=api('/git/blobs',dict(content=content,encoding='base64'))
 assert response['sha']==sha
 state['blobs'].append(sha);save()
 if number%8==0:print(f"Published {number}/{len(package['blobs'])} verified blobs",flush=True)
parent=package['base'];exported_parent=package['base']
parent_tree=api('/git/commits/'+parent)['tree']['sha']
for index,commit in enumerate(package['commits']):
 assert commit['parent']==exported_parent
 message=commit['message'];assert len(message)<=80 and '\n' not in message
 assert not any(word in message.lower() for word in ['co-authored','co authored','authored-by','authored by','ai attribution','generated by ai','generated by codex'])
 if index<len(state['commits']):
  mapped=state['commits'][index];assert mapped['exported']==commit['sha']
  parent=mapped['published'];parent_tree=commit['tree'];exported_parent=commit['sha'];continue
 # GitHub rejects an empty tree update. Preserve original empty commits by
 # reusing their parent's verified tree, rather than dropping their history.
 tree=(api('/git/trees',dict(base_tree=parent_tree,tree=commit['delta']))
       if commit['delta'] else dict(sha=parent_tree))
 assert tree['sha']==commit['tree'],(commit['sha'],'Tree differs from runner-verified snapshot')
 result=api('/git/commits',dict(message=message,tree=tree['sha'],parents=[parent],
          author=commit['author'],committer=commit['committer']))
 assert result['message']==message and result['tree']['sha']==commit['tree']
 assert [p['sha'] for p in result['parents']]==[parent]
 for key in ['author','committer']:
  assert result[key]['name']==commit[key]['name'] and result[key]['email']==commit[key]['email']
  assert datetime.fromisoformat(result[key]['date'].replace('Z','+00:00')) == datetime.fromisoformat(commit[key]['date'])
 state['commits'].append(dict(exported=commit['sha'],published=result['sha'],tree=commit['tree']))
 parent=result['sha'];parent_tree=commit['tree'];exported_parent=commit['sha'];save()
 if (index+1)%8==0:print(f"Published {index+1}/{len(package['commits'])} verified commits",flush=True)
assert parent_tree==package['tree'] and exported_parent==package['head']
if args.expected_old:
 current=api('/git/ref/heads/'+branch)['object']['sha']
 assert current in {args.expected_old,parent}, 'Preparation branch changed unexpectedly'
 repository=api('')['node_id']
 result=api('',dict(query='mutation($repo:ID!,$updates:[RefUpdate!]!){updateRefs(input:{repositoryId:$repo,refUpdates:$updates}){clientMutationId}}',
            variables=dict(repo=repository,updates=[dict(name='refs/heads/'+branch,beforeOid=current,afterOid=parent,force=True)])),graphql=True)
 assert not result.get('errors'),result
else:
 # The create operation is atomic and refuses any existing branch.
 probe=subprocess.run(['gh','api',REPO+'/git/ref/heads/'+branch],capture_output=True,text=True)
 if probe.returncode==0:
  assert json.loads(probe.stdout)['object']['sha']==parent, 'Preparation branch already exists at an unexpected head'
 else:
  assert '404' in probe.stderr, probe.stderr
  result=api('/git/refs',dict(ref='refs/heads/'+branch,sha=parent))
  assert result['object']['sha']==parent
assert api('/git/ref/heads/'+branch)['object']['sha']==parent
state.update(head=parent,tree=parent_tree,stage='Verified exported history published; final exact-head production gates required')
save();print(parent,flush=True)
